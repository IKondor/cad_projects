"""Все входные и производные размеры проекта. Правь тут.

Ничего не строит и не считает прочность — только числа. Импортируется
модулем целиком (`import variables as v`).

Три исполнения отличаются РОВНО одним числом — количеством отсеков хранения
справа от станции (см. `VARIANTS` внизу). Всё остальное — общее: глубина,
высоты, сечения, узлы. Поэтому геометрия в `poof.py` написана один раз.

Система координат: начало — левый ПЕРЕДНИЙ нижний угол габарита.
    X — ширина, вправо, если смотреть на пуфик спереди,
    Y — вглубь, к стене (Y = 0 — передняя плоскость, откуда заезжает робот),
    Z — высота от пола.

Описание конструкции и обоснование решений — см. README.md, исходное ТЗ — TODO.md.
"""

from dataclasses import dataclass

# --- Робот-пылесос и его станция -------------------------------------------
# Xiaomi Mijia M40 (D110CN) со станцией самоочистки.
#
# Замеры из ТЗ и официальные данные расходятся на единицы миллиметров:
#     ширина   350 (замер)  /  360 (паспорт)
#     глубина  460 (замер)  /  470 (паспорт)
#     высота   600 (замер)  /  572 (паспорт)
# Расхождение объясняется тем, что паспорт даёт корпус, а замер — с учётом
# выступов (кабель, защёлка бака). Берём МАКСИМУМ из двух по каждой оси:
# ошибка в большую сторону стоит десяток миллиметров пустоты, в меньшую —
# станция не влезает и переделывается весь корпус.

ST_W = 360.0  # ширина станции целиком
ST_D = 470.0  # глубина станции целиком: башня + поддон перед ней
ST_H = 600.0  # высота башни

TOWER_D = 260.0  # глубина одной башни, без поддона
TOWER_W = 350.0  # ширина башни (уже поддона)

SLOT_W = 360.0  # щель, в которую заезжает робот: ширина
SLOT_H = 150.0  # ... и высота
TRAY_H = 45.0  # высота поддона под роботом — оценка, на габарит не влияет

# --- Монтажные зазоры вокруг станции ---------------------------------------
# Станция не встраивается намертво: её надо занести внутрь, выставить,
# вынуть на обслуживание. Плюс она СУШИТ швабру горячим воздухом — глухой
# ящик без продуха станции противопоказан.

GAP_ST_SIDE = 20.0  # с каждого бока
GAP_ST_BACK = 25.0  # сзади: вилка с кабелем, выход воздуха
GAP_ST_TOP = 25.0  # сверху: снять крышку бака, не упираясь в сиденье
GAP_TOWER_FRONT = 10.0  # от передней грани башни до средней рамы

ROBOT_CLEAR = 160.0  # минимальный просвет под ступенью: щель 150 + запас

# --- Материалы -------------------------------------------------------------

# Брус каркаса, квадратного сечения. По прочности на 120 кг хватает и 40×40
# (расчёт печатает model.py), 50×50 — если брус берётся строганый и хочется
# запаса на выборку четверти под обшивку. Меняется одним числом.
BEAM = 40.0

T_OSB = 8.0  # ОСП обшивки — она только закрывает каркас, ничего не несёт

# Настил ступени и дно отсеков — МДФ 16. Плита несущая: по ней ходят ногами,
# поэтому её пролёт разбит продольными рёбрами (см. STEP_RIBS ниже) —
# на полной ширине отсека МДФ 16 под ногой в 120 кг НЕ ПРОХОДИТ.
T_FLOOR = 16.0
FLOOR_MAT = "МДФ"

# Рёбра под настилом ступени в отсеке станции: продольные бруски, которые
# делят его пролёт. Лежат на уровне поперечин, роботу под ними свободно.
# Одного хватает впритык (прогиб 0,8 при допуске 1,0), два дают запас втрое
# и стоят 0,4 п.м бруса — расчёт обоих вариантов печатает model.py.
STEP_RIBS = 2

# Крышка-сиденье. МДФ 16 мм под 120 кг НЕ ПРОХОДИТ по прогибу даже на
# коротком пролёте (расчёт в model.py), поэтому 22 — нижняя рабочая граница.
# 34 мм тоже годится, но это лишние 3 кг на откидной створке.
T_LID = 22.0

FOAM = 30.0  # поролон на сиденье
FOAM_SQUEEZED = 20.0  # он же под весом сидящего — по нему и считается высота

# --- Эргономика ------------------------------------------------------------

# Высота верха ступени. Она работает ДВАЖДЫ: как подножка сидящему (комфортно,
# когда сиденье выше неё примерно на длину голени, 400–430 мм) и как ступень,
# чтобы забраться на пуфик ногами. Снизу ограничена просветом для робота.
STEP_H = 260.0

# Вынос ступени вперёд за габарит верхнего блока. При 0 проступь получается
# около 190 мм — как у ступени стремянки: стоять можно, но не всей стопой.
# Поставь 60, если хочешь нормативные 250 мм проступи; глубина изделия
# вырастет на столько же.
STEP_FORWARD = 0.0

SEAT_LOAD = 120.0  # на пуфик встают ногами, кг
STORAGE_LOAD = 20.0  # барахло в отсеке хранения, кг
# Зазор между соседними крышками. Чётное число: половина уходит на каждую
# створку, и ширина крышек остаётся в целых миллиметрах.
LID_GAP = 4.0

# --- Отсеки ----------------------------------------------------------------

BAY_STORE = 250.0  # ширина одного отсека хранения в свету

# --- Цвет ------------------------------------------------------------------
# Влияет ТОЛЬКО на просмотр и картинки: ткань и цвет выбираются сильно позже.

PALETTE = "осп"

PALETTES: dict[str, dict[str, str]] = {
    "осп": {"каркас": "#d8bd8e", "крышка": "#b98f4e"},
    "серый": {"каркас": "#b9bec2", "крышка": "#8d9499"},
    "тёмный": {"каркас": "#6f665c", "крышка": "#4a433c"},
}

# --- Производные размеры: глубина ------------------------------------------
# Считаем от передней плоскости каркаса (Y = 0 при STEP_FORWARD = 0).

D_IN = GAP_ST_BACK + ST_D  # внутренняя глубина отсека станции
Y_BACK_POST = BEAM + D_IN  # левая (передняя) грань задних стоек
Y_BACK = Y_BACK_POST + BEAM + T_OSB  # задняя плоскость габарита

ST_Y0 = BEAM  # станция стоит вплотную к передним стойкам
ST_Y1 = ST_Y0 + ST_D
TOWER_Y0 = ST_Y1 - TOWER_D  # передняя грань башни

# Средняя рама несёт передний край сиденья и задний край ступени. Её верхняя
# поперечина проходит НАД поддоном станции, но не должна упереться в башню —
# отсюда предел по глубине ступени.
Y_MID = TOWER_Y0 - GAP_TOWER_FRONT - BEAM
Y_FRONT = -STEP_FORWARD  # передняя плоскость ступени

D_TOTAL = Y_BACK - Y_FRONT  # габаритная глубина изделия
SEAT_D = Y_BACK - (Y_MID - T_OSB)  # глубина сиденья
STEP_TREAD = (Y_MID - T_OSB) - Y_FRONT  # проступь: ступень перед подступёнком

# --- Производные размеры: высота -------------------------------------------

Z_FRAME_TOP = ST_H + GAP_ST_TOP  # верх обвязки = низ крышки
Z_POST_TOP = Z_FRAME_TOP - BEAM  # верх стоек: обвязка ложится на них сверху
SEAT_H = Z_FRAME_TOP + T_LID  # жёсткая высота сиденья
SEAT_H_SOFT = SEAT_H + FOAM_SQUEEZED  # она же с продавленным поролоном

Z_FLOOR_TOP = STEP_H  # верх настила ступени и дна отсеков
Z_FLOOR_BOT = STEP_H - T_FLOOR  # низ настила
Z_STEP_BEAM = Z_FLOOR_BOT - BEAM  # низ поперечин ступени — он же потолок гаража

ROBOT_PASS = Z_STEP_BEAM  # реальный просвет для робота
STORE_H = Z_FRAME_TOP - Z_FLOOR_TOP  # высота отсека хранения в свету
NICHE_H = Z_STEP_BEAM  # высота ниши под ступенью (обувь)
FOOT_DROP = SEAT_H_SOFT - STEP_H  # от сиденья до подножки

# --- Производные размеры: ширина -------------------------------------------

BAY_ST = ST_W + 2 * GAP_ST_SIDE  # отсек станции в свету
X_BAY_ST = T_OSB + BEAM  # левая грань отсека станции


def frame_width(bays: int) -> float:
    """Ширина каркаса (без обшивки) при `bays` отсеках хранения."""
    return BEAM + BAY_ST + bays * (BEAM + BAY_STORE) + BEAM


def total_width(bays: int) -> float:
    """Габаритная ширина изделия."""
    return frame_width(bays) + 2 * T_OSB


# --- Исполнения ------------------------------------------------------------


@dataclass(frozen=True)
class Variant:
    """Одно исполнение пуфика. Отличается только числом отсеков хранения."""

    key: str  # имя файлов в out/
    title: str  # как называть в отчёте
    bays: int  # отсеков хранения справа от станции

    @property
    def width(self) -> float:
        return total_width(self.bays)

    @property
    def seats(self) -> int:
        """Сколько человек садится: ~450 мм ширины на человека."""
        return max(1, int(self.width // 450))


VARIANTS: list[Variant] = [
    Variant("poof-compact", "Компакт — только станция", bays=0),
    Variant("poof-storage", "С отсеком хранения", bays=1),
    Variant("poof-bench", "Банкетка: станция и два отсека", bays=2),
]

# --- Проверки --------------------------------------------------------------

ROBOT_FITS = ROBOT_PASS >= ROBOT_CLEAR and BAY_ST >= SLOT_W
TOWER_CLEARS_MID = Y_MID + BEAM <= TOWER_Y0  # средняя поперечина не бьёт в башню
TOP_CLEARS_STATION = Z_POST_TOP >= 0  # обвязка выше станции по построению

# Пролёты, по которым считается прочность.
# Крышка опирается на обвязку по всем четырём сторонам: плита работает
# по КОРОТКОМУ пролёту, длинный лишь помогает. Берём короткий.
LID_SPAN_Y = Y_BACK_POST - (Y_MID + BEAM)  # в свету между средней и задней обвязкой
# Настил ступени в отсеке станции разбит на равные пролёты продольными
# рёбрами — по ним и считается прогиб.
STEP_SPAN = BAY_ST / (STEP_RIBS + 1)
