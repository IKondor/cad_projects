"""Куб 2×2×2 метра — шаблон для новых проектов.

Запуск:
    uv run python projects/starter-cube/model.py

Структура ниже — рекомендуемый скелет любого проекта монорепо:
параметры сверху отдельным блоком, построение в функции, экспорт и просмотр
под `if __name__ == "__main__"`. Так модель можно и импортировать из другого
скрипта (например, чтобы посчитать спецификацию), и запустить напрямую.
"""

import cadquery as cq

from cadkit import export, show

# --- Параметры -------------------------------------------------------------
# Все размеры в МИЛЛИМЕТРАХ. Это соглашение всего монорепо.

SIDE = 2000.0  # ребро куба, мм (= 2 м)


# --- Построение ------------------------------------------------------------


def build(side: float = SIDE) -> cq.Workplane:
    """Куб с ребром `side`, центрированный в начале координат."""
    return cq.Workplane("XY").box(side, side, side)


# --- Точка входа -----------------------------------------------------------

if __name__ == "__main__":
    model = build()

    volume_m3 = model.val().Volume() / 1e9
    print(f"Куб {SIDE / 1000:g}×{SIDE / 1000:g}×{SIDE / 1000:g} м, объём {volume_m3:g} м³")

    for path in export(model, "cube", __file__):
        print(f"  → {path}")

    show(model, names=["cube"])
